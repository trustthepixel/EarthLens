"""Create an Ed25519 device key for a TPX2 source (microcontroller or Raspberry Pi).

The seed stays with the device. The ground station only needs the public key, which this script
writes to ``trusted_keys/``. Optionally it also writes a C header for the ESP32 firmware.

Run from the project root::

    python -m scripts.make_device_key --name esp32cam --c-header firmware/device_seed.h

Demonstration-grade key storage: the seed is kept in a file and in firmware flash.
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

from tp.device_protocol import key_id_bytes

ROOT = Path(__file__).resolve().parents[1]


def c_header(seed: bytes, key_id: str) -> str:
    rows = [', '.join(f'0x{b:02x}' for b in seed[i:i + 8]) for i in range(0, 32, 8)]
    body = ',\n  '.join(rows)
    return (f'// Generated by scripts.make_device_key. Keep this file private; do not commit it.\n'
            f'#pragma once\n#define TP_KEY_ID_HEX "{key_id}"\nstatic const unsigned char TP_SEED[32] = {{\n  {body}\n}};\n')


def provision(root: Path, name: str, force: bool = False, c_header_path: Path | None = None):
    if not re.fullmatch(r'[a-z0-9_-]{1,24}', name):
        raise ValueError('name must be 1 to 24 characters: a-z, 0-9, _ or -')
    seed_path = root / 'keys' / f'device_{name}.seed.hex'
    public_path = root / 'trusted_keys' / f'device_{name}.pem'
    if not force and (seed_path.exists() or public_path.exists()):
        raise FileExistsError('A key with this name already exists; use --force to replace it.')
    seed = os.urandom(32)
    sk = Ed25519PrivateKey.from_private_bytes(seed)
    seed_path.parent.mkdir(parents=True, exist_ok=True)
    public_path.parent.mkdir(parents=True, exist_ok=True)
    seed_path.write_text(seed.hex() + '\n', encoding='utf-8')
    if os.name != 'nt':
        seed_path.chmod(0o600)
    public_path.write_bytes(sk.public_key().public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo))
    key_id = key_id_bytes(sk.public_key()).hex()
    if c_header_path:
        c_header_path.parent.mkdir(parents=True, exist_ok=True)
        c_header_path.write_text(c_header(seed, key_id), encoding='utf-8')
    return seed_path, public_path, key_id


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--name', required=True, help='device name, for example esp32cam or pi')
    parser.add_argument('--force', action='store_true')
    parser.add_argument('--c-header', type=Path, help='also write a C header with the seed for firmware')
    parser.add_argument('--root', type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        seed_path, public_path, key_id = provision(args.root, args.name, args.force, args.c_header)
    except Exception as exc:
        print(f'Key creation failed: {type(exc).__name__}: {exc}', file=sys.stderr)
        return 1
    print(f'Seed written to {seed_path.relative_to(args.root).as_posix()} (keep it private).')
    print(f'Public key written to {public_path.relative_to(args.root).as_posix()} (key id {key_id}).')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
